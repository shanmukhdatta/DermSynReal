"""Frozen PanDerm official encoder + sklearn linear probe inference.

Model code, checkpoint, and joblib file must come from trusted, separately supplied
sources. The official encoder is not interchangeable with timm. GPU required for
practical inference. This module never trains or picks hyperparameters.
"""
from __future__ import annotations
import csv
import hashlib
import json
import sys
from argparse import Namespace
from pathlib import Path
from .evaluation import _label
from .inference import _read_manifest, TRAIN_ORDER


def run_panderm_inference(*, official_repo, official_weights, saved_probe,
                          model_details, real_manifest, real_image_root, out_csv,
                          synthetic_manifest=None, synthetic_image_root=None,
                          train_synthetic_manifest=None, batch_size=4, num_workers=2,
                          allow_test=False):
    if not allow_test:
        raise ValueError("Final test locked until all model choices are frozen")
    repo=Path(official_repo)
    if not (repo/"classification"/"models").is_dir():
        raise FileNotFoundError("Provide exact official PanDerm repository folder")
    weight_path=Path(official_weights)
    if not weight_path.is_file():
        raise FileNotFoundError("Attach genuine official PanDerm pretrained weights")
    meta=json.loads(Path(model_details).read_text(encoding="utf-8"))
    if meta.get("encoder")!="PanDerm_Base_LP" or [str(x).lower() for x in meta.get("labels",[])]!=list(TRAIN_ORDER):
        raise ValueError("PanDerm training metadata or label order mismatch")
    if meta.get("checkpoint_name")!=weight_path.name:
        raise ValueError("PanDerm checkpoint filename mismatch")
    import numpy as np
    import joblib
    import torch
    from PIL import Image,ImageOps
    from torch.utils.data import Dataset, DataLoader
    # Import official builder exactly as the existing training notebook does.
    official_classification=str((repo/"classification").resolve())
    if official_classification not in sys.path: sys.path.insert(0,official_classification)
    from models import get_encoder
    device=torch.device("cuda" if torch.cuda.is_available() else "cpu")
    encoder,transform=get_encoder(Namespace(pretrained_checkpoint=str(weight_path)),"PanDerm_Base_LP")
    encoder=encoder.to(device).eval()
    for parameter in encoder.parameters():parameter.requires_grad=False
    # Only ever load joblib from a trusted artifact generated by our own notebook.
    probe=joblib.load(saved_probe)
    if not hasattr(probe,"predict_proba") or not hasattr(probe,"classes_"):
        raise ValueError("Saved PanDerm probe must support predict_proba and classes_")
    classes=[int(x) for x in probe.classes_]
    if sorted(classes)!=list(range(6)):
        raise ValueError(f"PanDerm probe's six learned labels are incomplete: {classes}")
    real=_read_manifest(real_manifest,domain="real")
    parts=[(r,"real",Path(real_image_root)) for r in real]
    if synthetic_manifest:
        if not synthetic_image_root:raise ValueError("synthetic_image_root required")
        syn=_read_manifest(synthetic_manifest,domain="synthetic",
                           other_ids={r["image_id"] for r in real},
                           train_synthetic_manifest=train_synthetic_manifest)
        parts.extend((r,"synthetic",Path(synthetic_image_root)) for r in syn)
    class ImageSet(Dataset):
        def __len__(self):return len(parts)
        def __getitem__(self,index):
            record,source,root=parts[index]
            given=Path(record["image_path"])
            path=given if given.is_absolute() else root/given
            if not path.is_file():raise FileNotFoundError(path)
            with Image.open(path) as im:
                im.load()
                if min(im.size)<64:raise ValueError(f"Image too small: {path}")
                rgb=ImageOps.exif_transpose(im).convert("RGB")
                if np.asarray(rgb).std()<2 or np.asarray(rgb).mean()<3:
                    raise ValueError(f"Blank/black facial image: {path}")
                return transform(rgb), index
    dl=DataLoader(ImageSet(),batch_size=batch_size,shuffle=False,num_workers=num_workers,
                  pin_memory=device.type=="cuda")
    probability=[None]*len(parts)
    with torch.inference_mode():
        for xb,positions in dl:
            vectors=encoder.forward_features(xb.to(device),is_train=False)
            if vectors.ndim!=2:
                raise ValueError(f"Unexpected PanDerm feature shape {tuple(vectors.shape)}")
            probs=np.asarray(probe.predict_proba(vectors.float().cpu().numpy()))
            for k,p in zip(positions.tolist(),probs):
                dest=np.zeros(6,dtype=float)
                for col,class_index in enumerate(classes):dest[class_index]=p[col]
                if not np.all(np.isfinite(dest)) or abs(float(dest.sum())-1)>0.002:
                    raise ValueError("Invalid PanDerm probabilities")
                probability[k]=dest
    cols=["image_id","true_label","pred_label","source","split","group_id",
          "dataset_source","prompt_family_id"]+["p_"+s for s in TRAIN_ORDER]
    rows=[]
    for index,(record,domain,_) in enumerate(parts):
        p=probability[index]
        if p is None:raise RuntimeError("Incomplete inference")
        row={"image_id":record["image_id"],"true_label":_label(record["label"]),
             "pred_label":_label(TRAIN_ORDER[int(np.argmax(p))]),
             "source":domain,"split":"test","group_id":record["group_id"],
             "dataset_source":record.get("dataset_source",""),
             "prompt_family_id":record.get("prompt_family_id","")}
        row.update({"p_"+s:float(p[j]) for j,s in enumerate(TRAIN_ORDER)})
        rows.append(row)
    target=Path(out_csv);target.parent.mkdir(parents=True,exist_ok=True)
    with target.open("w",newline="",encoding="utf-8") as output:
        writer=csv.DictWriter(output,fieldnames=cols);writer.writeheader();writer.writerows(rows)
    proof={"encoder":"PanDerm_Base_LP","official_repo":str(repo),
           "weights_sha256":hashlib.sha256(weight_path.read_bytes()).hexdigest(),
           "probe_sha256":hashlib.sha256(Path(saved_probe).read_bytes()).hexdigest(),
           "model_details_sha256":hashlib.sha256(Path(model_details).read_bytes()).hexdigest(),
           "real_manifest_sha256":hashlib.sha256(Path(real_manifest).read_bytes()).hexdigest(),
           "rows":len(rows),"device":str(device),"locked_final_test":True,
           "note":"Official PanDerm features and trained linear probe only; not full fine-tuning."}
    target.with_suffix(".provenance.json").write_text(json.dumps(proof,indent=2)+"\n")
    return proof
